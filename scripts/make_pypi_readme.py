#!/usr/bin/env python3
"""Generate PYPI-README.md from README.md with absolute URLs.

PyPI renders the long description in isolation: relative paths have nothing to resolve
against, so every figure 404s and every doc link dies. It also runs the Markdown through a
sanitiser that strips raw ``<img>`` tags outright — the logo does not merely break, it
disappears.

So README.md stays as-is (clean relative links, which is what GitHub wants) and this script
emits the PyPI variant:

* images  → ``raw.githubusercontent.com/<repo>/<ref>/<path>``
* links   → ``github.com/<repo>/blob/<ref>/<path>``
* ``<img src=…>`` → a Markdown image, which survives the sanitiser

``<ref>`` defaults to the version tag from pyproject.toml, so the page published for 0.1.1
keeps showing 0.1.1's figures even after main moves on. **The tag must be pushed before the
release goes live**, or the URLs resolve to nothing.

    python scripts/make_pypi_readme.py            # ref = v<version from pyproject>
    python scripts/make_pypi_readme.py --ref main
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "numberingeometry/brontide"
RAW = "https://raw.githubusercontent.com/{repo}/{ref}/{path}"
BLOB = "https://github.com/{repo}/blob/{ref}/{path}"
BANNER = "<!-- GENERATED by scripts/make_pypi_readme.py from README.md. DO NOT EDIT. -->\n"

IMAGE_SUFFIXES = {".png", ".gif", ".jpg", ".jpeg", ".svg", ".webp"}


def _version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return data["project"]["version"]


def _is_external(target: str) -> bool:
    return target.startswith(("http://", "https://", "mailto:", "#"))


def convert(text: str, ref: str, repo: str = REPO) -> str:
    def raw(path: str) -> str:
        return RAW.format(repo=repo, ref=ref, path=path.lstrip("./"))

    def blob(path: str) -> str:
        return BLOB.format(repo=repo, ref=ref, path=path.lstrip("./"))

    # <img src="assets/x.svg" …> → ![](raw)  — the sanitiser drops the tag form entirely
    def img_tag(m: re.Match) -> str:
        src = m.group(1)
        return f"![]({src if _is_external(src) else raw(src)})"

    text = re.sub(r'<img\s+src="([^"]+)"[^>]*>', img_tag, text)

    # ![alt](path) → raw
    def md_image(m: re.Match) -> str:
        alt, tgt = m.group(1), m.group(2)
        return f"![{alt}]({tgt if _is_external(tgt) else raw(tgt)})"

    text = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", md_image, text)

    # [text](path) → blob   (negative lookbehind keeps images out)
    def md_link(m: re.Match) -> str:
        label, tgt = m.group(1), m.group(2)
        if _is_external(tgt):
            return m.group(0)
        anchor = ""
        if "#" in tgt:
            tgt, anchor = tgt.split("#", 1)
            anchor = "#" + anchor
        target = raw(tgt) if Path(tgt).suffix.lower() in IMAGE_SUFFIXES else blob(tgt)
        return f"[{label}]({target}{anchor})"

    return re.sub(r"(?<!!)\[([^\]]+)\]\(([^)]+)\)", md_link, text)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ref", default=None, help="git ref for the URLs (default: v<version>)")
    ap.add_argument("--out", default=ROOT / "PYPI-README.md", type=Path)
    args = ap.parse_args()
    ref = args.ref or f"v{_version()}"

    src = (ROOT / "README.md").read_text(encoding="utf-8")
    out = BANNER + convert(src, ref)
    args.out.write_text(out, encoding="utf-8")

    remaining = [
        t for t in re.findall(r"!?\[[^\]]*\]\(([^)]+)\)", out) if not _is_external(t)
    ]
    n_img = len(re.findall(r"!\[[^\]]*\]\(", out))
    n_link = len(re.findall(r"(?<!!)\[[^\]]+\]\(", out))
    print(f"wrote {args.out.relative_to(ROOT)}  (ref={ref})")
    print(f"  {n_img} images, {n_link} links")
    if remaining:
        print(f"  !! {len(remaining)} still relative: {remaining[:5]}")
        return 1
    print("  all targets absolute")
    return 0


if __name__ == "__main__":
    sys.exit(main())
